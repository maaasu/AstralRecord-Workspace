it('shows the active workspace and retains edited inputs across navigation', async () => {
  vi.spyOn(window, 'confirm').mockReturnValue(true)
  render(<App />)
  const nav = within(await screen.findByRole('navigation', { name: '開発ツール' }))
  expect(nav.getAllByRole('button')).toHaveLength(6)
  expect(within(nav.getByRole('group', { name: 'データ・配置編集' })).getAllByRole('button').map(button => button.textContent)).toEqual(['マスターデータ', 'スキルツリー', 'ワールド配置・編集'])
  expect(within(nav.getByRole('group', { name: '設計・分析' })).getAllByRole('button').map(button => button.textContent)).toEqual(['装備・入手経路', 'ゲーム進行フロー', '比較・成長グラフ'])
  expect(nav.getByRole('button', { name: 'マスターデータ' })).toHaveAttribute('aria-current', 'page')
  expect(window.astralEditorHasUnsavedChanges?.()).toBe(false)
  const draft = await screen.findByLabelText('マスターの下書き')
  fireEvent.change(draft, { target: { value: '編集中の値' } })
  expect(nav.getByRole('button', { name: 'マスターデータ ●' })).toHaveAttribute('aria-pressed', 'true')
  expect(window.astralEditorHasUnsavedChanges?.()).toBe(true)
  fireEvent.click(nav.getByRole('button', { name: 'スキルツリー' }))
  await screen.findByLabelText('ツリーの下書き')
  expect(draft).not.toBeVisible()
  expect(nav.getByRole('button', { name: 'スキルツリー' })).toHaveAttribute('aria-current', 'page')
  expect(nav.getByRole('button', { name: 'マスターデータ ●' })).not.toHaveAttribute('aria-current')
  fireEvent.click(nav.getByRole('button', { name: 'マスターデータ ●' }))
  expect(screen.getByLabelText('マスターの下書き')).toBe(draft)
  expect(draft).toHaveValue('編集中の値')
  await waitFor(() => expect(draft).toBeVisible())
  expect(window.astralEditorHasUnsavedChanges?.()).toBe(true)
})

it('hides and restores the editing navigation without changing the current page', async () => {
  render(<App />)
  const draft = await screen.findByLabelText('マスターの下書き')
  const toggle = screen.getByRole('button', { name: '編集ナビゲーション' })
  fireEvent.click(toggle)
  expect(toggle).toHaveAttribute('aria-pressed', 'false')
  expect(screen.queryByRole('navigation', { name: '開発ツール' })).not.toBeInTheDocument()
  expect(draft).toBeVisible()
  fireEvent.click(toggle)
  expect(await screen.findByRole('navigation', { name: '開発ツール' })).toBeVisible()
  expect(toggle).toHaveAttribute('aria-pressed', 'true')
})

it('opens desktop panels from the keyboard and keeps workspace and popout commands in the command bar', async () => {
  const user = userEvent.setup()
  const postMessage = vi.fn()
  vi.stubGlobal('chrome', { webview: { postMessage } })
  vi.spyOn(toolJobApi, 'capabilities').mockResolvedValue({
    enabled: true, reason: null, workspaceRoot: 'C:/worktrees/editor-fixture', activeRunId: null,
  })
  const openPopout = vi.spyOn(DockviewApi.prototype, 'addPopoutGroup').mockResolvedValue(true)
  render(<App />)
  const bar = within(screen.getByRole('banner'))
  expect(bar.getByRole('button', { name: '編集ナビゲーション' })).toHaveAttribute('aria-pressed', 'true')
  const workspace = bar.getByRole('button', { name: 'ワークスペースを変更' })
  expect(await bar.findByText('editor-fixture')).toBeVisible()
  expect(workspace).toHaveAttribute('title', 'C:/worktrees/editor-fixture')
  await user.click(workspace)
  expect(postMessage).toHaveBeenCalledWith('select-workspace')

  const trigger = bar.getByRole('button', { name: 'パネル' })
  const popout = bar.getByRole('button', { name: '別ウィンドウで開く' })
  trigger.focus()
  await user.keyboard('{ArrowDown}')
  const menu = within(screen.getByRole('menu', { name: 'パネル' }))
  const first = menu.getByRole('menuitem', { name: 'マスターデータ' })
  const reset = menu.getByRole('menuitem', { name: 'レイアウトを初期化' })
  expect(first).toHaveFocus()
  expect(menu.queryByRole('menuitem', { name: /編集ナビ/ })).not.toBeInTheDocument()
  await user.keyboard('{End}')
  expect(reset).toHaveFocus()
  await user.keyboard('{Home}')
  expect(first).toHaveFocus()
  await user.keyboard('{ArrowUp}')
  expect(reset).toHaveFocus()
  await user.keyboard('{Escape}')
  expect(trigger).toHaveFocus()
  expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await user.keyboard('{ArrowUp}')
  const reopenedReset = screen.getByRole('menuitem', { name: 'レイアウトを初期化' })
  expect(reopenedReset).toHaveFocus()
  fireEvent.keyDown(reopenedReset, { key: 'Tab' })
  expect(trigger).toHaveFocus()
  await user.tab()
  expect(popout).toHaveFocus()
  expect(screen.queryByRole('menu')).not.toBeInTheDocument()

  trigger.focus()
  await user.keyboard('{ArrowDown}{ArrowDown}{ArrowDown}{ArrowDown}{ArrowDown}{ArrowDown}{Enter}')
  expect(await screen.findByText('比較の作業領域')).toBeVisible()
  expect(trigger).toHaveFocus()
  await user.click(popout)
  expect(openPopout).toHaveBeenCalledWith(expect.objectContaining({ id: 'analytics' }), expect.objectContaining({ position: expect.any(Object) }))
})
